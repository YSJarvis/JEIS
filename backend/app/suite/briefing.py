def to_pdf(d: dict) -> bytes:
    limits = {"segments": 7, "booths": 8, "grievances": 6, "promises": 4, "threats": 4, "actions": 6}
    # fit each page on its own: trim rows until page 1 and page 2 are one page each
    for part, keys in ((1, ("booths", "segments")), (2, ("promises", "grievances", "actions", "threats"))):
        for _ in range(20):
            if _render(d, limits, only=part)[1] <= 1:
                break
            key = max((k for k in keys if limits[k] > 2), key=lambda k: limits[k], default=None)
            if key is None:
                break
            limits[key] -= 1
    return _render(d, limits)[0]


def _render(d: dict, lim: dict, only: int | None = None) -> tuple[bytes, int]:
    from reportlab.graphics.shapes import Drawing, Rect, String
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle)

    font = _unicode_font()
    base, bold = (font, f"{font}-Bold") if font else ("Helvetica", "Helvetica-Bold")
    C = colors.HexColor

    def clean(t) -> str:
        t = str(t if t is not None else "")
        if not font:
            for a, b in (("₹", "Rs "), ("“", '"'), ("”", '"'), ("’", "'"), ("‘", "'"), ("–", "-"), ("—", "-"), ("…", "..."), ("·", "-")):
                t = t.replace(a, b)
            t = t.encode("latin-1", "replace").decode("latin-1")
        return escape(t)

    def short(t, n):
        t = str(t or "")
        return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"

    st = {
        "kicker": ParagraphStyle("k", fontName=bold, fontSize=7.5, leading=9, textColor=C(VIOLET)),
        "h1": ParagraphStyle("h1", fontName=bold, fontSize=18, leading=21, textColor=C(INK)),
        "sub": ParagraphStyle("sub", fontName=base, fontSize=8, leading=10.5, textColor=C(MUTED)),
        "h2": ParagraphStyle("h2", fontName=bold, fontSize=11.5, leading=14, textColor=C(INK), spaceBefore=7, spaceAfter=1),
        "prod": ParagraphStyle("prod", fontName=bold, fontSize=7, leading=8.5, textColor=C(VIOLET)),
        "h3": ParagraphStyle("h3", fontName=bold, fontSize=8.8, leading=11, textColor=C(INK), spaceBefore=4, spaceAfter=2),
        "body": ParagraphStyle("b", fontName=base, fontSize=8.8, leading=12, textColor=C(INK)),
        "cell": ParagraphStyle("c", fontName=base, fontSize=7.6, leading=9.4, textColor=C(INK)),
        "cellb": ParagraphStyle("cb", fontName=bold, fontSize=7.6, leading=9.4, textColor=C(INK)),
        "cellm": ParagraphStyle("cm", fontName=base, fontSize=6.8, leading=8.4, textColor=C(MUTED)),
        "head": ParagraphStyle("hd", fontName=bold, fontSize=6.8, leading=8.4, textColor=C(MUTED)),
        "li": ParagraphStyle("li", fontName=base, fontSize=8.6, leading=11.4, textColor=C(INK), leftIndent=10, bulletIndent=0, spaceAfter=1.5),
        "kpi": ParagraphStyle("kpi", fontName=bold, fontSize=17, leading=19, textColor=C(INK)),
        "kpil": ParagraphStyle("kpil", fontName=base, fontSize=7, leading=8.6, textColor=C(MUTED)),
        "banner": ParagraphStyle("bn", fontName=bold, fontSize=8, leading=10, textColor=colors.white),
    }
    P = lambda t, s="cell": Paragraph(clean(t), st[s])          # noqa: E731
    PR = lambda t, s="cell": Paragraph(t, st[s])                # noqa: E731  (pre-escaped markup)
    W = A4[0] - 30 * mm

    def table(rows, widths, head=True, zebra=True):
        t = Table(rows, colWidths=widths, repeatRows=1 if head else 0)
        style = [("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                 ("TOPPADDING", (0, 0), (-1, -1), 2.2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.2),
                 ("LINEBELOW", (0, 0), (-1, 0 if head else -1), 0.6, C(LINE))]
        if zebra:
            style += [("BACKGROUND", (0, i), (-1, i), C("#F7F7F5")) for i in range(2 if head else 1, len(rows), 2)]
        t.setStyle(TableStyle(style))
        return t

    def section(product, title):
        return [Spacer(0, 2 * mm), P(product.upper(), "prod"), P(title, "h2")]

    a, k, f = d["area"], d["kpis"], d["field"]
    story = []

    # ---------------- page 1 ----------------
    story += [P("JARVIS ELECTION INTELLIGENCE SUITE · EXECUTIVE BRIEFING", "kicker"),
              P(f"{a.label}: campaign position", "h1"),
              P(f"Prepared {d['generated'].strftime('%d %b %Y, %H:%M')} IST · VoterEngine AI · JanVani Copilot · CounterPulse AI", "sub")]
    if d["workspace"] == "demo" or d["sample_data"]:
        msg = ("PITCH DEMO: every figure in this briefing is synthetic." if d["workspace"] == "demo"
               else "Contains SAMPLE data (sample documents or media). Remove sample material before operational use.")
        bt = Table([[P(msg, "banner")]], colWidths=[W])
        bt.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), C(AMBER)), ("LEFTPADDING", (0, 0), (-1, -1), 6),
                                ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
        story += [Spacer(0, 2 * mm), bt]
    tiles = [
        (fmt(k["persuade"]), "Priority voters to persuade", f"{fmt(k['gotv'])} supporters to turn out"),
        (f"{k['booths_covered_today']}/{k['active_booths']}", "Booths with cadres today", f"{f['progress']}% of {fmt(f['planned'])} doors done"),
        (str(k["manifestos"]), "Local manifestos generated", f"{k['briefs']} speech brief{'s' if k['briefs'] != 1 else ''}"),
        (str(k["critical_threats"]), "Critical narrative threats", f"{k['high_threats']} high, {k['active_narratives']} active"),
    ]
    tt = Table([[[P(v, "kpi"), P(l, "cellb"), P(s, "kpil")] for v, l, s in tiles]], colWidths=[W / 4] * 4)
    tt.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, C(LINE)), ("INNERGRID", (0, 0), (-1, -1), 0.6, C(LINE)),
                            ("LEFTPADDING", (0, 0), (-1, -1), 7), ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                            ("LINEABOVE", (3, 0), (3, 0), 2.2, C(SEV_COLOR["Critical"] if k["critical_threats"] else LINE))]))
    story += [Spacer(0, 3 * mm), tt, Spacer(0, 2.5 * mm)]
    story += [P("Situation", "h3")] + [Paragraph(clean(s), st["li"], bulletText="•") for s in summary(d)]

    if d["by_state"]:
        rows = [[P(h, "head") for h in ("State", "Booths", "Persuadable", "Supporters to turn out", "Manifestos", "Critical / high threats")]]
        for s in d["by_state"]:
            rows.append([P(s["name"], "cellb"), P(s["active_booths"]), P(fmt(s["persuade"])), P(fmt(s["gotv"])), P(s["manifestos"]),
                         P(f"{s['critical_threats']} / {s['high_threats']}")])
        story += [Spacer(0, 1.5 * mm), table(rows, [W * x for x in (0.24, 0.1, 0.16, 0.2, 0.12, 0.18)])]

    story += section("VoterEngine AI", "1. Target voter segments and booth turnout priorities")
    total = sum(q["voters"] for q in d["quadrants"]) or 1
    dr = Drawing(W, 30)
    x = 0
    for q in d["quadrants"]:
        w = W * q["voters"] / total
        dr.add(Rect(x, 14, max(w - 1, 0), 12, fillColor=C(Q_COLOR[q["quadrant"]]), strokeColor=None))
        if w > 70:
            dr.add(String(x + 3, 3, f"{Q_SHORT[q['quadrant']]} {q['share']}%", fontName=base, fontSize=6.8, fillColor=C(MUTED)))
        x += w
    story.append(dr)
    rows = [[P(h, "head") for h in ("Segment", "Voters", "Persuadable", "Avg turnout score", "Recommended play")]]
    for s in d["segments"][: lim["segments"]]:
        rows.append([P(s["segment"], "cellb"), P(fmt(s["voters"])), P(f"{fmt(s['persuade'])} ({s['persuade_share']}%)"),
                     P(s["avg_turnout"]), P(play(s))])
    story += [P("Segments (age, gender, scheme use, migration; no caste or religion profiling)", "h3"),
              table(rows, [W * x for x in (0.3, 0.1, 0.17, 0.15, 0.28)])]
    rows = [[P(h, "head") for h in ("Booth", "Constituency", "Past turnout", "Last margin", "To persuade", "To turn out", "Priority", "Focus")]]
    for b in d["booths"][: lim["booths"]]:
        rows.append([PR(f"<b>{clean(b['booth_id'])}</b><br/><font size=6.5 color='{MUTED}'>{clean(short(b['name'], 34))}</font>"),
                     P(f"{b['constituency']}, {b['state']}"), P(f"{b['historical_turnout']:.0f}%"),
                     P(f"{b['last_margin_pct']:.1f}%" if b["last_margin_pct"] is not None else "–"), P(fmt(b["persuade"])), P(fmt(b["gotv"])),
                     P(f"{b['priority_score']:.0f}"), P(b["focus"])])
    story += [P("Booth turnout priorities (ranked by margin, turnout gap and persuadable share)", "h3"),
              table(rows, [W * x for x in (0.2, 0.17, 0.09, 0.09, 0.1, 0.1, 0.08, 0.17)])]
    story.append(PageBreak())

    # ---------------- page 2 ----------------
    story += section("JanVani Copilot", "2. Top constituency grievances and key campaign promises")
    if d["grievances"]:
        rows = [[P(h, "head") for h in ("Constituency", "Grievance", "Evidence", "Source")]]
        chosen = d["grievances"][: lim["grievances"]]
        order = list(STATES)
        chosen = sorted(chosen, key=lambda g: (order.index(g["constituency_id"].split("-")[0]), g["constituency"], g["_rank"]))
        for g in chosen:
            rows.append([P(g["constituency"], "cellb"), P(g["title"], "cellb"),
                         PR(clean(short(g["context"], 125)).replace(clean(g["figure"]), f"<b>{clean(g['figure'])}</b>", 1)
                            if g["figure"] and g["figure"] in g["context"]
                            else (f"<b>{clean(g['figure'])}</b> " if g["figure"] else "") + clean(short(g["context"], 110))),
                         P(short(re.sub(r"^SAMPLE:\s*", "Sample: ", g["source"]), 70), "cellm")])
        story.append(table(rows, [W * x for x in (0.14, 0.2, 0.42, 0.24)]))
    else:
        story.append(P("No speech brief has been generated for this area yet. Generate one in JanVani Copilot to put local grievances on record.", "body"))
    if d["promises"]:
        story.append(P("Key campaign promises (from party commitment documents in the knowledge base)", "h3"))
        story += [Paragraph(f"{clean(p['text'])} <font size=6.8 color='{MUTED}'>({clean(p['scope'])})</font>", st["li"], bulletText="•")
                  for p in d["promises"][: lim["promises"]]]

    story += section("CounterPulse AI", "3. Media sentiment and active crisis counter-strategies")
    s = d["sentiment"]
    if s["items"]:
        story.append(P(f"{fmt(s['items'])} media items in the last {s['days']} days: {s['negative_share']}% negative, "
                       f"{fmt(s['neutral'])} neutral, {fmt(s['positive'])} positive.", "body"))
        bars = Drawing(W, 13 * len(s["by_source"][:5]) + 4)
        mx = max(sum(r[x] for x in ("negative", "neutral", "positive")) for r in s["by_source"]) or 1
        for i, r in enumerate(s["by_source"][:5]):
            y = bars.height - 12 - i * 13
            bars.add(String(0, y + 2, r["source"], fontName=base, fontSize=7, fillColor=C(MUTED)))
            x0 = 60
            for key, col in (("negative", AMBER), ("neutral", "#A8A3B8"), ("positive", TEAL)):
                w = (W * 0.55) * r[key] / mx
                if w:
                    bars.add(Rect(x0, y, w - 0.8, 9, fillColor=C(col), strokeColor=None)); x0 += w
            bars.add(String(x0 + 4, y + 2, f"{r['negative']} neg · {r['neutral']} neutral · {r['positive']} pos", fontName=base,
                            fontSize=6.6, fillColor=C(MUTED)))
        story += [Spacer(0, 1 * mm), bars]
    if d["threats"]:
        rows = [[P(h, "head") for h in ("Narrative", "Threat", "What is being claimed", "Counter-strategy")]]
        for t in d["threats"][: lim["threats"]]:
            r = t["response"]
            if r:
                strat = (f"<b>{clean(r['verdict'])}.</b> {clean(short(r['lead_fact'], 120))} "
                         f"<font color='{TEAL if r['status'] == 'approved' else AMBER}'>{clean(r['medium_label'] or '')}: "
                         f"{'approved' if r['status'] == 'approved' else 'awaiting approval'}</font>")
            else:
                strat = f"<font color='{AMBER}'>No counter-brief yet.</font> Generate a TV brief and a WhatsApp broadcast from verified facts."
            claim = t["claim"] or "(coverage mainly in Hindi or Punjabi; see the war room)"
            rows.append([PR(f"<b>{clean(t['label'])}</b><br/><font size=6.5 color='{MUTED}'>{clean(STATES[t['state']]['name'] if t['state'] else 'National')} · {t['items_24h']} items in 24 h</font>"),
                         PR(f"<font color='{SEV_COLOR[t['severity']]}'><b>{t['threat_score']}</b></font><br/><font size=6.5>{t['severity']}</font>"),
                         P(short(claim, 130)), PR(strat)])
        tb = table(rows, [W * x for x in (0.22, 0.08, 0.32, 0.38)])
        story.append(Spacer(0, 1.5 * mm)); story.append(tb)
    else:
        story.append(P("No active narratives in this area.", "body"))

    acts = next_actions(d)[: lim["actions"]]
    if acts:
        story += [Spacer(0, 2 * mm), P("Next 72 hours", "h2")] + [Paragraph(clean(x), st["li"], bulletText=f"{i}.") for i, x in enumerate(acts, 1)]

    pages = {"n": 0}
    if only:
        cut = next(i for i, x in enumerate(story) if isinstance(x, PageBreak))
        story = story[:cut] if only == 1 else story[cut + 1:]

    def decorate(canvas, doc):
        pages["n"] = doc.page
        canvas.saveState()
        canvas.setFillColor(C(VIOLET)); canvas.rect(0, A4[1] - 4, A4[0], 4, fill=1, stroke=0)
        canvas.setFont(base, 6.6); canvas.setFillColor(C(MUTED))
        canvas.drawString(15 * mm, 9 * mm, FOOTER[0])
        canvas.drawString(15 * mm, 6 * mm, FOOTER[1])
        canvas.drawRightString(A4[0] - 15 * mm, 9 * mm, f"Page {doc.page} of 2" if not only else "")
        if d["workspace"] == "demo":
            canvas.setFont(bold, 46); canvas.setFillColor(C("#EDEBF2"))
            canvas.translate(A4[0] / 2, A4[1] / 2); canvas.rotate(35)
            canvas.drawCentredString(0, 0, "PITCH DEMO")
        canvas.restoreState()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=12 * mm, bottomMargin=14 * mm,
                            title=f"Executive Briefing: {a.label}", author="Jarvis Election Intelligence Suite")
    doc.build(story, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue(), pages["n"]
