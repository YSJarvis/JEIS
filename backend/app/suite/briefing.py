SEV_COLOR = {"Critical": "#6B2D0A", "High": "#A1620C", "Medium": "#C9A25A", "Low": "#BDB9C6"}
Q_COLOR = {"PERSUADE": "#5B2E91", "GOTV": "#0F766E", "LOW": "#A8A3B8", "OPPOSITION": "#5E5A6B"}
Q_SHORT = {"PERSUADE": "Persuadable", "GOTV": "Supporters to turn out", "LOW": "Neutral, low turnout", "OPPOSITION": "Opposition core"}
def play(s: dict) -> str:
    gotv_share = 100 * s["gotv"] / s["voters"] if s["voters"] else 0
    if s["persuade_share"] >= 20:
        return "Persuasion: issue conversations at the door"
    if gotv_share >= 8:
        return "Turnout: reminders and booth-day transport"
    return "Light touch: scheme-delivery follow-up"


def mlabel(x: str | None) -> str:
    """'Official press release' -> 'official press release'; keeps 'TV …' and 'WhatsApp …'."""
    x = x or "response"
    return x if x.split()[0] in ("TV", "WhatsApp") else x[0].lower() + x[1:]


def article(x: str) -> str:
    return "an" if x[:1].lower() in "aeiou" else "a"
FOOTER = ["Aggregates only: no voter-level personal data (DPDP Act 2023). Generated by the Jarvis Election Intelligence Suite.",
          "Public material must follow the Model Code of Conduct; paid political advertising needs MCMC pre-certification."]


def gather(c, area: Area, workspace: str = "main") -> dict:
    k = command.kpis(c, area)
    f = command.field_today(c, area)
    threats = command.narratives(c, area, 6)
    return {
        "area": area, "workspace": workspace, "generated": datetime.now(ZoneInfo(TIMEZONE)),
        "kpis": k, "field": f, "quadrants": command.quadrants(c, area), "segments": command.segments(c, area),
        "booths": command.top_booths(c, area, 8), "grievances": _spread(command.grievances(c, area, 3, 4)),
        "promises": command.promises(c, area, 5), "sentiment": command.sentiment(c, area), "threats": threats,
        "pending": command.pending_approvals(c, area),
        "by_state": command.by_state(c) if len(area.states) > 1 else None,
        "sample_data": _has_sample(c),
    }


def _spread(rows: list[dict]) -> list[dict]:
    """Interleave places so a trimmed table still covers every constituency: 1st issue of each, then 2nd…"""
    rank, seen = [], {}
    for g in rows:
        seen[g["constituency_id"]] = seen.get(g["constituency_id"], -1) + 1
        rank.append((seen[g["constituency_id"]], g))
    picked = [g for _, g in sorted(rank, key=lambda x: x[0])]
    for i, g in enumerate(picked):
        g["_rank"] = i
    return picked


def _has_sample(c) -> bool:
    docs = c.execute("SELECT COUNT(*) FROM copilot_documents WHERE active = 1 AND source_citation LIKE 'SAMPLE%'").fetchone()[0]
    media = c.execute("SELECT COUNT(*) FROM media_items WHERE channel LIKE '%(sample)%'").fetchone()[0]
    return bool(docs or media)


def fmt(n) -> str:
    """Indian digit grouping: 1,23,456."""
    n = int(round(n or 0))
    s = str(abs(n))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        head = re.sub(r"(\d)(?=(\d\d)+$)", r"\1,", head)
        s = f"{head},{tail}"
    return ("-" if n < 0 else "") + s


def summary(d: dict) -> list[str]:
    k, f, a = d["kpis"], d["field"], d["area"]
    total = sum(q["voters"] for q in d["quadrants"]) or 1
    where = "all four states" if len(a.states) == len(STATES) and not a.constituency else a.label
    out = [f"Across {where}, {fmt(k['persuade'])} voters ({round(100 * k['persuade'] / total)}%) are persuadable and likely "
           f"to vote, and {fmt(k['gotv'])} supporters are at risk of not turning out."]
    if f["planned"]:
        out.append(f"Today {f['cadres_dispatched']} of {f['cadres']} cadres are on route and have completed {f['progress']}% of "
                   f"{fmt(f['planned'])} planned doors, recording {fmt(f['consents_granted_today'])} consents.")
    else:
        out.append(f"No cadre routes have been dispatched today ({f['cadres']} cadres available).")
    if d["threats"]:
        t = d["threats"][0]
        r = t["response"]
        resp = (f"{article(mlabel(r['medium_label']))} {mlabel(r['medium_label'])} is {'approved' if r['status'] == 'approved' else 'drafted, awaiting approval'}"
                if r else "no counter-response has been drafted yet")
        out.append(f"The top narrative threat is “{t['label']}” in {STATES[t['state']]['name'] if t['state'] else 'national media'} "
                   f"({t['threat_score']}/100, {t['severity']}); {resp}.")
    else:
        out.append("No active narrative threats are being tracked.")
    out.append(f"JanVani Copilot holds {k['manifestos']} local manifesto{'s' if k['manifestos'] != 1 else ''} and "
               f"{k['briefs']} speech brief{'s' if k['briefs'] != 1 else ''} for this area.")
    return out


def next_actions(d: dict) -> list[str]:
    k, f = d["kpis"], d["field"]
    out = []
    if f["cadres"] - f["cadres_dispatched"] > 0:
        out.append(f"Dispatch routes to the {f['cadres'] - f['cadres_dispatched']} cadres not yet in the field today.")
    persuade_booths = [b for b in d["booths"] if b["focus"] == "Persuasion visits"][:3]
    if persuade_booths:
        out.append("Concentrate persuasion visits on " + ", ".join(f"{b['name'].split(' (')[0]} ({b['booth_id']})" for b in persuade_booths) + ".")
    turnout_booths = [b for b in d["booths"] if b["focus"] == "Turnout drive"][:2]
    if turnout_booths:
        out.append("Plan turnout drives for " + ", ".join(b["booth_id"] for b in turnout_booths) + ", where loyal supporters outnumber persuadable voters.")
    for t in d["threats"][:2]:
        if t["severity"] in ("Critical", "High"):
            r = t["response"]
            if not r:
                out.append(f"Draft and approve a counter-response to “{t['label']}” within 24 hours.")
            elif r["status"] != "approved":
                out.append(f"Approve or revise the drafted {mlabel(r['medium_label'])} on “{t['label']}”.")
            else:
                out.append(f"Release the approved {mlabel(r['medium_label'])} on “{t['label']}” and track its threat score over 48 hours.")
    if d["pending"]:
        out.append(f"{d['pending']} counter-brief draft{'s are' if d['pending'] != 1 else ' is'} waiting for war-room approval.")
    if not d["grievances"]:
        out.append("Generate a speech brief in JanVani Copilot so local grievances are on record.")
    return out[:6]


