# Markdown
# ---------------------------------------------------------------------------

def to_markdown(kind: str, p: dict) -> str:
    c = p["constituency"]
    out = []
    if kind == "brief":
        out += [f"# {p['event_label']}: {c['name']}", "",
                f"**Audience:** {p['audience_label']} · **State:** {c['state']} · **Date:** {_when(p)}"
                + (f" · **Party:** {p['party_name']}" if p.get("party_name") else ""), "",
                "## Executive summary", "", _marks(p["executive_summary"]["text"]), "", "## Key local grievances", ""]
        for i, g in enumerate(p["grievances"], 1):
            out += [f"### {i}. {g['title']}", "", _marks(g["detail"]), ""]
            for st in g["stats"]:
                out.append(f"- **{st['figure']}**: {_marks(st['context'])} [{st['source']}]")
            out.append("")
        if p["opponent_critique"]:
            out += ["## Record-based critique", ""] + [f"- {_marks(x['point'])}" for x in p["opponent_critique"]] + [""]
        out += ["## Commitments", ""]
        for x in p["commitments"]:
            refs = "".join(f" [{s}]" for s in x["sources"] if f"[{s}]" not in x["commitment"])
            out.append(f"- **{'Party' if x['type'] == 'party' else 'Local'}:** {_marks(x['commitment'])}{refs}"
                       + (f"  \n  _Delivery:_ {x['delivery']}" if x.get("delivery") else ""))
        out += ["", f"## {p['event_section']['title']}", ""]
        out += [f"{i}. {_marks(it['text'])}" for i, it in enumerate(p["event_section"]["items"], 1)] + [""]
    else:
        out += [f"# {p['title']}", "", f"**Area:** {c['name']}, {c['state']} · **Date:** {_when(p)}"
                + (f" · **Party:** {p['party_name']}" if p.get("party_name") else ""), ""]
        if p["preamble"]["text"]:
            out += [_marks(p["preamble"]["text"]), ""]
        for sec in p["sections"]:
            out += [f"## {sec['topic']}", "", f"_What we found:_ {_marks(sec['local_context'])}", ""]
            for x in sec["commitments"]:
                refs = "".join(f" [{s}]" for s in x["sources"] if f"[{s}]" not in x["text"])
                out.append(f"- {_marks(x['text'])}{refs}" + (f"  \n  _How:_ {x['delivery']}" if x.get("delivery") else ""))
            out.append("")
        if p.get("closing"):
            out += [p["closing"], ""]
    used = [s for s in p["sources"] if s["used"]]
    out += ["---", "", "## Sources", ""] + [f"- **[{s['id']}]** {s['citation']}" + (f" ({s['url']})" if s.get("url") else "")
                                            for s in used]
    if p.get("warnings"):
        out += ["", "## Review notes", ""] + [f"- {w}" for w in p["warnings"]]
    out += ["", f"_{DISCLAIMER}_", ""]
    return "\n".join(out)


