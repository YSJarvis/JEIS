def to_pdf(kind: str, p: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer

    if p.get("generated_language", "en") != "en":
        raise ValueError("PDF export supports English drafts. Use Print (it handles Hindi and Punjabi script) or Markdown.")
    font = _unicode_font()
    base, bold = (font, f"{font}-Bold") if font else ("Helvetica", "Helvetica-Bold")

    def clean(t: str) -> str:
        t = str(t or "")
        if not font:
            t = t.replace("₹", "Rs ").replace("“", '"').replace("”", '"').replace("’", "'").replace("‘", "'").replace("–", "-").replace("—", "-").replace("…", "...")
        try:
            (t if font else t.encode("latin-1"))
        except UnicodeEncodeError:
            raise ValueError("This draft contains characters the PDF font can't show. Use Print or Markdown.") from None
        return escape(t)

    def cite(t: str) -> str:
        return re.sub(r"\[(S\d+)\]", r"<font size=7 color='#5B2E91'>[\1]</font>", clean(t))

    ss = getSampleStyleSheet()
    ink, violet, muted = colors.HexColor("#1D1A2E"), colors.HexColor("#5B2E91"), colors.HexColor("#6B6779")
    H1 = ParagraphStyle("h1", parent=ss["Title"], fontName=bold, fontSize=19, leading=23, alignment=0, textColor=ink, spaceAfter=2)
    H2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName=bold, fontSize=12.5, leading=16, textColor=violet, spaceBefore=9, spaceAfter=3)
    H3 = ParagraphStyle("h3", parent=ss["Heading3"], fontName=bold, fontSize=11, leading=14, textColor=ink, spaceBefore=5, spaceAfter=1)
    B = ParagraphStyle("b", parent=ss["Normal"], fontName=base, fontSize=10, leading=14, textColor=ink)
    S = ParagraphStyle("s", parent=B, fontSize=8.5, leading=11.5, textColor=muted)
    LI = ParagraphStyle("li", parent=B, leftIndent=10, bulletIndent=0, spaceAfter=2)

    buf = io.BytesIO()
    c = p["constituency"]
    title = f"{p['event_label']}: {c['name']}" if kind == "brief" else p["title"]
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=title, author="JanVani Copilot")
    st = [Paragraph(clean(title), H1)]
    if kind == "brief":
        st.append(Paragraph(clean(f"For {p['audience_label'].lower()} · {c['state']} · {_when(p)}"
                                  + (f" · {p['party_name']}" if p.get("party_name") else "")), S))
        st += [Paragraph("Executive summary", H2), Paragraph(cite(p["executive_summary"]["text"]), B),
               Paragraph("Key local grievances", H2)]
        for i, g in enumerate(p["grievances"], 1):
            block = [Paragraph(clean(f"{i}. {g['title']}"), H3), Paragraph(cite(g["detail"]), B)]
            block += [Paragraph(f"<b>{clean(x['figure'])}</b>: {cite(x['context'])} <font size=7 color='#5B2E91'>[{x['source']}]</font>",
                                LI, bulletText="•") for x in g["stats"]]
            st.append(KeepTogether(block))
        if p["opponent_critique"]:
            st.append(Paragraph("Record-based critique", H2))
            st += [Paragraph(cite(x["point"]), LI, bulletText="•") for x in p["opponent_critique"]]
        st.append(Paragraph("Commitments", H2))
        for x in p["commitments"]:
            st.append(Paragraph(f"<b>{'Party' if x['type'] == 'party' else 'Local'}:</b> {cite(x['commitment'])}"
                                + (f"<br/><font color='#6B6779'>Delivery: {clean(x['delivery'])}</font>" if x.get("delivery") else ""),
                                LI, bulletText="•"))
        st.append(Paragraph(clean(p["event_section"]["title"]), H2))
        st += [Paragraph(cite(it["text"]), LI, bulletText=f"{i}.") for i, it in enumerate(p["event_section"]["items"], 1)]
    else:
        st.append(Paragraph(clean(f"{c['name']}, {c['state']} · {_when(p)}" + (f" · {p['party_name']}" if p.get("party_name") else "")), S))
        if p["preamble"]["text"]:
            st += [Spacer(0, 3 * mm), Paragraph(cite(p["preamble"]["text"]), B)]
        for sec in p["sections"]:
            block = [Paragraph(clean(sec["topic"]), H2), Paragraph(f"<i>What we found:</i> {cite(sec['local_context'])}", B)]
            block += [Paragraph(cite(x["text"]) + (f"<br/><font color='#6B6779'>How: {clean(x['delivery'])}</font>" if x.get("delivery") else ""),
                                LI, bulletText="•") for x in sec["commitments"]]
            st.append(KeepTogether(block))
        if p.get("closing"):
            st += [Spacer(0, 3 * mm), Paragraph(clean(p["closing"]), B)]
    used = [s for s in p["sources"] if s["used"]]
    st += [Spacer(0, 4 * mm), Paragraph("Sources", H2)]
    st += [Paragraph(f"<b>[{s['id']}]</b> {clean(s['citation'])}", S) for s in used]
    st += [Spacer(0, 3 * mm), Paragraph(clean(DISCLAIMER), S)]
    doc.build(st)
    return buf.getvalue()
