"""Exports for saved Copilot drafts: Markdown (any language) and PDF (Latin script).

The PDF uses reportlab's built-in fonts, which have no Devanagari or Gurmukhi
glyphs and no complex-script shaping, so Hindi/Punjabi drafts are exported as
Markdown or printed from the browser (which shapes Indic text correctly).
"""
from __future__ import annotations

import io
import os
import re
from datetime import datetime
from xml.sax.saxutils import escape

DISCLAIMER = ("Draft generated by JanVani Copilot from the cited sources. Check every figure against its source and "
              "review the wording before public use.")
_UNICODE_FONT = None


def _unicode_font():
    """Register DejaVu Sans if the system has it (gives ₹ and smart quotes)."""
    global _UNICODE_FONT
    if _UNICODE_FONT is not None:
        return _UNICODE_FONT or None
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    for path in [os.environ.get("VOTERENGINE_PDF_FONT", ""), "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                 "/Library/Fonts/DejaVuSans.ttf", "C:/Windows/Fonts/DejaVuSans.ttf"]:
        if path and os.path.exists(path):
            bold = path.replace("DejaVuSans.ttf", "DejaVuSans-Bold.ttf")
            pdfmetrics.registerFont(TTFont("VEUni", path))
            pdfmetrics.registerFont(TTFont("VEUni-Bold", bold if os.path.exists(bold) else path))
            _UNICODE_FONT = "VEUni"
            return _UNICODE_FONT
    _UNICODE_FONT = ""
    return None


def _marks(text: str) -> str:
    return re.sub(r"\[(S\d+)\]", r"[\1]", text or "")


def _when(payload) -> str:
    try:
        return datetime.fromisoformat(payload["generated_at"]).strftime("%d %b %Y")
    except (KeyError, ValueError):
        return ""


